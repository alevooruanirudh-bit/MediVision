"""EXPERIMENTAL report engine: our self-trained CNN + Transformer decoder (IU X-ray), with a clinical
consistency check against the chest classifier's positive findings."""

from __future__ import annotations

import threading
from functools import lru_cache
from typing import Any

import numpy as np

from app.config import DISCLAIMER
from app.inference.registry import registry
from ml.data.transforms import preprocess
from ml.train_report import mentioned_findings

_lock = threading.Lock()


@lru_cache
def _tokenizer(path: str) -> Any:
    from tokenizers import Tokenizer

    return Tokenizer.from_file(path)


def available() -> bool:
    return registry.get("report_gen") is not None


def generate(img: np.ndarray, results: dict[str, Any]) -> dict[str, Any]:
    import torch

    h = registry.get("report_gen")
    if h is None:
        raise RuntimeError("experimental report model is not trained")
    tok = _tokenizer(str(h.path / "tokenizer.json"))
    model = h.torch_model()
    x = torch.from_numpy(preprocess(img, h.img_size))
    with _lock, torch.no_grad():
        ids = model.generate(
            x, tok.token_to_id("<bos>"), tok.token_to_id("<eos>"), max_new=90, beam=3
        )[0]
    text = " ".join(tok.decode(ids).split())
    findings_txt, impression_txt = text, ""
    if "impression:" in text:
        findings_txt, impression_txt = (t.strip() for t in text.split("impression:", 1))
    findings_txt = findings_txt.replace("findings:", "").strip()
    gen = mentioned_findings(text)
    clf = {f["key"] for f in results.get("findings", []) if f.get("positive")}
    agree = gen & clf
    consistency = {
        "generated_mentions": sorted(gen),
        "classifier_positives": sorted(clf),
        "agreement": sorted(agree),
        "only_in_text": sorted(gen - clf),
        "only_in_classifier": sorted(clf - gen),
        "score": round(len(agree) / max(len(gen | clf), 1), 3) if (gen | clf) else 1.0,
    }
    m = h.metrics.get("test", {})
    return {
        "indication": "Not provided.",
        "technique": "Single frontal chest radiograph.",
        "findings": {"Generated findings": _cap(findings_txt) or "(empty)"},
        "measurements": ["Not produced by the experimental engine."],
        "impression": [f"1. {_cap(impression_txt or findings_txt)}"],
        "recommendations": [
            "Experimental free-text output — verify every statement against the image "
            "and the rule-based report."
        ],
        "ai_confidence": [
            "EXPERIMENTAL: generated by our small Transformer decoder trained from scratch on ~2.6k IU "
            "X-ray reports.",
            f"Test BLEU-4 {m.get('bleu4', 0):.3f}, ROUGE-L {m.get('rouge_l', 0):.3f}.",
            f"Clinical consistency with the classifier: {consistency['score']:.0%} "
            f"(text-only mentions: {', '.join(consistency['only_in_text']) or 'none'}; "
            f"classifier-only: {', '.join(consistency['only_in_classifier']) or 'none'}).",
        ],
        "disclaimer": DISCLAIMER
        + " Experimental generated text — may contain errors (hallucinations).",
        "meta": {"engine": "experimental", "consistency": consistency, "raw": text},
    }


def _cap(s: str) -> str:
    s = s.strip()
    return (s[0].upper() + s[1:]) if s else s
