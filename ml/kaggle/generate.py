def metadata(model: str, smoke: bool = False) -> dict[str, Any]:
    members = PLANS[model].get("members", [model])
    k = load_config(CONFIG_OF.get(model, model), "full").get("kaggle", {})
    datasets = sorted(
        {
            s
            for m in members
            for s in load_config(m, "full").get("kaggle", {}).get("dataset_sources", [])
        }
    )
    if model == "router":
        datasets = k.get("dataset_sources", [])
    slug = f"medivision-{model.replace('_', '-')}" + ("-smoke" if smoke else "")
    return {
        "id": f"USERNAME/{slug}",
        "title": slug,
        "code_file": "notebook.ipynb",
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": datasets,
        "competition_sources": k.get("competition_sources", []),
        "kernel_sources": [],
    }


def generate(models: list[str] | None = None, smoke: bool = False) -> list[Path]:
    out = []
    for m in models or list(PLANS):
        d = HERE / (m + ("_smoke" if smoke else ""))
        d.mkdir(exist_ok=True)
        (d / "notebook.ipynb").write_text(json.dumps(notebook(m, smoke), indent=1))
        (d / "kernel-metadata.json").write_text(json.dumps(metadata(m, smoke), indent=2))
        out.append(d)
    print(f"[kaggle] generated {len(out)} notebook(s) in {HERE}")
    return out


