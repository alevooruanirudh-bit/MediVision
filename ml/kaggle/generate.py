def bundle() -> str:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for p in sorted((ROOT / "ml").rglob("*")):
            rel = p.relative_to(ROOT)
            if p.is_dir() or "__pycache__" in p.parts or rel.parts[1] in ("kaggle", "tests"):
                continue
            if p.suffix in (".py", ".yaml", ".md", ".jsonl") or p.name == "SOURCES.md":
                tar.add(p, arcname=str(rel))
        tar.add(ROOT / "requirements.txt", arcname="requirements.txt")
    return base64.b64encode(buf.getvalue()).decode()


def _cell(src: str, kind: str = "code") -> dict[str, Any]:
    c: dict[str, Any] = {
        "cell_type": kind,
        "metadata": {},
        "source": src.strip("\n").splitlines(True),
    }
    if kind == "code":
        c.update({"execution_count": None, "outputs": []})
    return c


